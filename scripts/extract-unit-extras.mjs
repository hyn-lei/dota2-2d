// Recover gameplay fields that the initial stat-table extractor did not include.
import fs from 'node:fs';
import { NEUTRAL_UNITS, NEUTRAL_ABILITIES } from '../src/unit-data.js';
function parse(raw){
  const tokens=[...raw.replace(/\/\/[^\n]*/g,'').matchAll(/"((?:\\.|[^"\\])*)"|([{}])/g)].map(m=>m[2]||m[1]);let i=0;
  function object(){const result={};while(i<tokens.length){const key=tokens[i++];if(key==='}')return result;const value=tokens[i++];result[key]=value==='{'?object():value;}return result;}
  return object();
}
const units=JSON.parse(fs.readFileSync('docs/research/units/parsed-units.json','utf8'));
const abilities=parse(fs.readFileSync('docs/research/units/npc_abilities.txt','utf8')).DOTAAbilities;
const unitExtras={},abilityExtras={};
for(const [key,data]of Object.entries(NEUTRAL_UNITS)){
  const raw={...units.npc_dota_units_base,...units[data.sourceId]};
  unitExtras[key]={maxMana:Number(raw.StatusMana)||0,manaRegen:Number(raw.StatusManaRegen)||0,visionDay:Number(raw.VisionDaytimeRange)||0,visionNight:Number(raw.VisionNighttimeRange)||0};
}
for(const key of Object.keys(NEUTRAL_ABILITIES)){
  const raw=abilities[key]||{};
  abilityExtras[key]={damage:raw.AbilityDamage||'0',damageType:raw.AbilityUnitDamageType||'DAMAGE_TYPE_MAGICAL',castPoint:raw.AbilityCastPoint||'0'};
}
fs.writeFileSync('src/unit-extras.js',`// Valve NPC KV snapshot fields, generated by scripts/extract-unit-extras.mjs.\nexport const UNIT_EXTRAS=${JSON.stringify(unitExtras)};\nexport const ABILITY_EXTRAS=${JSON.stringify(abilityExtras)};\n`);
console.log(`Extracted ${Object.keys(unitExtras).length} unit records and ${Object.keys(abilityExtras).length} ability records.`);
