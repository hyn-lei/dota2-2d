import fs from 'node:fs';
import { HERO_STATS } from '../src/hero-data.js';
import { BUILDING_STATS, LANE_CREEPS, NEUTRAL_UNITS } from '../src/unit-data.js';
function parse(text){const tokens=[...text.replace(/\/\/[^\n]*/g,'').matchAll(/"((?:\\.|[^"\\])*)"|([{}])/g)].map(m=>m[2]||m[1]);let i=0;function obj(){const out={};while(i<tokens.length){const k=tokens[i++];if(k==='}')return out;const v=tokens[i++];out[k]=v==='{'?obj():v;}return out;}return obj();}
const units=parse(fs.readFileSync('docs/research/attacks/npc_units.txt','utf8')).DOTAUnits;
const profiles={};
for(const stats of [...Object.values(BUILDING_STATS),...Object.values(LANE_CREEPS),...Object.values(NEUTRAL_UNITS)]){
 const raw=units[stats.sourceId];if(!raw||stats.range<=200)continue;
 profiles[stats.sourceId]={speed:Number(raw.ProjectileSpeed||900),attackPoint:Number(raw.AttackAnimationPoint||0),particle:raw.ProjectileModel||''};
}
for(const [id]of Object.entries(HERO_STATS)){
 const prefix=id==='windranger'?'windrunner':id;
 const raw=parse(fs.readFileSync(`docs/research/heroes/npc_dota_hero_${prefix}.txt`,'utf8')).DOTAHeroes[`npc_dota_hero_${prefix}`];
 profiles[id]={speed:Number(raw.ProjectileSpeed||0),attackPoint:Number(raw.AttackAnimationPoint||0),particle:raw.ProjectileModel||''};
}
const meta=JSON.parse(fs.readFileSync('docs/research/attacks/meta.json','utf8'));
fs.writeFileSync('src/attack-records.js',`// Generated by scripts/extract-attack-profiles.mjs from tracked Valve KV.\nexport const ATTACK_DATA_META=${JSON.stringify(meta,null,2)};\nexport const ATTACK_PROFILES=${JSON.stringify(profiles,null,2)};\n`);
console.log(`Extracted ${Object.keys(profiles).length} attack profiles.`);
