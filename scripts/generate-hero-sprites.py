"""Build a compact game atlas from the existing transparent hero renders.

Requires Pillow only when regenerating art: python scripts/generate-hero-sprites.py
The generated PNG and JavaScript data are committed; the game/build needs no Python.
"""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
HEROES = ['weaver', 'chaos_knight', 'juggernaut', 'crystal_maiden', 'windranger',
          'axe', 'ogre_magi', 'kunkka', 'chen', 'drow_ranger']
CELL, COLUMNS, PADDING = 384, 5, 4
MODEL_HEIGHTS = {'chaos_knight': 68, 'chen': 64, 'ogre_magi': 60,
                 'axe': 57, 'juggernaut': 56, 'kunkka': 56}
# Exposed weapon pixels only: never remove a hand, face, torso or mount.
# Coordinates refer to the tracked 1440px transparent source renders.
WEAPONS = {
    'axe': {'pivot': (520, 481), 'polygon': [(90, 255), (415, 245), (493, 414),
            (526, 457), (520, 513), (481, 507), (370, 510), (238, 455), (90, 355)]},
    'kunkka': {'pivot': (724, 778), 'polygon': [(90, 475), (371, 535),
               (497, 638), (624, 674), (714, 695), (750, 783),
               (732, 919), (625, 921), (610, 839), (443, 842), (170, 709)]},
    'chaos_knight': {'pivot': (526, 642), 'polygon': [(119, 659), (260, 541),
                    (461, 569), (529, 606), (533, 657), (420, 698),
                    (303, 765), (136, 831), (87, 811)]},
    'ogre_magi': {'pivot': (1105, 1105), 'polygon': [(961, 1120), (990, 1095),
                 (1020, 1090), (1036, 1121), (1085, 1140), (1140, 1110),
                 (1178, 1070), (1175, 990), (1218, 948), (1243, 960),
                 (1250, 1000), (1236, 1060), (1225, 1130), (1269, 1120),
                 (1399, 1202), (1391, 1250),
                 (1265, 1232), (1223, 1321), (981, 1370), (932, 1315), (942, 1148)]},
}
atlas = Image.new('RGBA', (CELL * COLUMNS, CELL * 2))
sprites = {}
for index, hero in enumerate(HEROES):
    image = Image.open(ROOT / 'assets' / (hero + '.png')).convert('RGBA')
    bounds = image.getchannel('A').getbbox()
    if not bounds:
        raise ValueError('Empty hero art: ' + hero)
    image = image.crop(bounds)
    ratio = image.width / image.height
    image.thumbnail((CELL - PADDING * 2, CELL - PADDING * 2), Image.Resampling.LANCZOS)
    x, y = index % COLUMNS * CELL + PADDING, index // COLUMNS * CELL + PADDING
    atlas.paste(image, (x, y))
    width = 84 if hero == 'weaver' else MODEL_HEIGHTS.get(hero, 54) * ratio
    height = width / ratio
    # Align humanoid/rider feet rather than the center of their weapon silhouette.
    # Weaver keeps its established spider-shaped footprint exactly.
    offset_x = 0
    if hero != 'weaver':
        alpha = image.getchannel('A')
        samples = [(px, alpha.getpixel((px, py)))
                   for py in range(int(image.height * .88), image.height)
                   for px in range(image.width) if alpha.getpixel((px, py)) >= 128]
        mass = sum(weight for _, weight in samples)
        center = sum(px * weight for px, weight in samples) / mass if mass else image.width / 2
        offset_x = (image.width / 2 - center) * width / image.width
    sprites[hero] = {'x': x, 'y': y, 'width': image.width, 'height': image.height,
                     'worldWidth': round(width, 4), 'worldHeight': round(height, 4),
                     'top': round(4 - height, 4), 'offsetX': round(offset_x, 4)}
    if hero in WEAPONS:
        def world_point(point):
            return [round((point[0] - bounds[0]) * width / (bounds[2] - bounds[0])
                          - width / 2 + offset_x, 4),
                    round((point[1] - bounds[1]) * height / (bounds[3] - bounds[1])
                          + 4 - height, 4)]
        sprites[hero]['weapon'] = {
            'pivot': world_point(WEAPONS[hero]['pivot']),
            'polygon': [world_point(point) for point in WEAPONS[hero]['polygon']],
        }
atlas.save(ROOT / 'assets' / 'hero-sprites.png', optimize=True)
data = '// Generated by scripts/generate-hero-sprites.py from existing hero art.\n'
data += 'export const HERO_SPRITES = ' + json.dumps(sprites, indent=2) + ';\n'
(ROOT / 'src' / 'hero-sprite-data.js').write_bytes(data.encode('utf-8'))
print(f'Hero atlas: {atlas.width}x{atlas.height}, {len(sprites)} heroes')
