import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const sourcePath=path.join(root,'docs/research/maps/7.42/terrain-sources.json');

export async function generateTerrain742(){
 const sources=JSON.parse(await readFile(sourcePath,'utf8'));
 const steamBuild=sources.verifiedClient?.steamBuild||sources.steamBuild;
 const resource=sources.resources.find(r=>r.vpkPath==='maps/dota.gnv');
 const raw=await readFile(path.join(root,resource.file));
 assert.equal(createHash('sha256').update(raw).digest('hex'),resource.sha256,'GridNav snapshot hash');
 assert.equal(raw.readUInt32LE(0),0xfadebead,'GridNav signature');
 const edge=raw.readFloatLE(4),offsetX=raw.readFloatLE(8),offsetY=raw.readFloatLE(12),
  width=raw.readInt32LE(16),height=raw.readInt32LE(20),minX=raw.readInt32LE(24),minY=raw.readInt32LE(28);
 assert.equal(edge,64);assert.ok(width>0&&height>0);assert.equal(raw.length,32+width*height);
 const cols=327,rows=327,blocked=[];let outside=0,count=0;
 for(let y=0;y<rows;y++){
  let line='';
  for(let x=0;x<cols;x++){
   const cx=(x*edge-10464-offsetX)/edge-minX,cy=(10400-y*edge-offsetY)/edge-minY;
   assert.ok(Number.isInteger(cx)&&Number.isInteger(cy),'Existing centers must map exactly to native GridNav centers');
   const valid=cx>=0&&cy>=0&&cx<width&&cy<height;
   if(!valid)outside++;
   const value=!valid||!(raw[32+cy*width+cx]&1)?'1':'0';line+=value;if(value==='1')count++;
  }
  blocked.push(line);
 }
 const meta={cellSize:edge,cols,rows,origin:{x:0,y:0},originX:0,originY:0,terrainOnly:true,
  geometryVersion:'7.42',blockedCount:count,source:resource.vpkPath,sourceSha256:resource.sha256,steamBuild,sourceSteamBuild:sources.steamBuild};
 const header=`/**\n * Valve 7.42 terrain traversal from the shipped maps/dota.gnv.\n * Exact existing world centers; Source Y reversed, outside grid blocked.\n * Traversable flag only; overlay trees, buildings and moving units separately.\n * Generated by docs/research/generate-map-terrain-742.mjs.\n * See docs/research/maps/7.42/terrain-sources.json and map-sources.md.\n */\n`;
 await writeFile(path.join(root,'src/nav-data.js'),header+'const blocked = [\n'+blocked.map(row=>`  '${row}',`).join('\n')+"\n].join('');\n\nexport const NAV_GRID = "+JSON.stringify(meta).replace(/}$/,',blocked };')+'\n');
 const mapFile=path.join(root,'src/map-data.js');let code=await readFile(mapFile,'utf8');
 const version=JSON.parse(code.match(/export const MAP_VERSION = ([^\n]+);/)[1]);
 Object.assign(version,{navigationGeometry:'7.42',navigationExtractedAt:sources.retrieved,navigationVerifiedAt:sources.verifiedAt||sources.retrieved,navigationVerifiedAgainstCurrentBinary:true,steamBuild});
 const image=sources.imageMode==='historical'?sources.historicalImage:sources.image;
 if(image){
  const bytes=await readFile(path.join(root,image.file));
  assert.equal(createHash('sha256').update(bytes).digest('hex'),image.sha256,'Terrain image snapshot hash');
  if(image.geometryVersion==='7.42'){
   assert.ok(bytes.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])),'Native overview must be the retained PNG');
   assert.equal(bytes.readUInt32BE(16),image.runtime.imageWidth);assert.equal(bytes.readUInt32BE(20),image.runtime.imageHeight);
  }
  await copyFile(path.join(root,image.file),path.join(root,image.runtime.url));
  code=code.replace(/export const MAP_IMAGE = [^\n]+;/,'export const MAP_IMAGE = '+JSON.stringify(image.runtime)+';');
  Object.assign(version,{geometry:image.geometryVersion,extractedAt:image.extractedAt,verifiedAt:sources.verifiedAt||sources.retrieved,imageGeometry:image.geometryVersion,imageExtractedAt:image.extractedAt,imageSourceVerified:true,
   imageRuntimeMaterialReferenceProven:image.explicitRuntimeMaterialReferenceProven,geometryVerifiedAgainstCurrentBinary:false});
 }
 code=code.replace(/export const MAP_VERSION = [^\n]+;/,'export const MAP_VERSION = '+JSON.stringify(version)+';')
  .replace('Navigation/terrain raster retains the 7.41 snapshot.','Navigation uses the 7.42 client; raster provenance is recorded in MAP_IMAGE.');
 await writeFile(mapFile,code);
 await writeFile(path.join(root,'docs/research/maps/7.42/terrain-validation.json'),JSON.stringify({patch:'7.42',steamBuild,sourceSteamBuild:sources.steamBuild,
  nativeGrid:{edge,offsetX,offsetY,width,height,minX,minY},runtimeGrid:meta,outsideSourceGridCount:outside,
  image:image?{file:image.runtime.url,sha256:image.sha256,worldRect:image.runtime.worldRect,geometryVersion:image.geometryVersion}:null},null,2)+'\n');
 console.log(`Generated Valve 7.42 navigation: ${cols}x${rows}, ${count} blocked cells; ${outside} outside native grid.`);
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await generateTerrain742();
