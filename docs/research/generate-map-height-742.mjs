import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {NAV_GRID} from '../../src/nav-data.js';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const missingHeight=-16384;
const coarseRecordBytes=9;
const runRecordBytes=6;

function readVhcg(raw){
 assert.equal(raw.toString('ascii',0,4),'vhcg');
 assert.equal(raw.readUInt32LE(4),1);
 const header=raw.readUInt32LE(8),width=raw.readUInt32LE(12),height=raw.readUInt32LE(16),
  detailWidth=raw.readUInt32LE(20),edge=raw.readFloatLE(24),originX=raw.readFloatLE(28),originY=raw.readFloatLE(32);
 assert.equal(header,128);
 assert.ok(raw.subarray(36,header).every(value=>value===0),'VHCG reserved bytes');
 assert.ok(width>0&&height>0&&detailWidth>1&&edge>0);
 const detailBytes=detailWidth**2*4;
 let detail=header+width*height*coarseRecordBytes;
 assert.ok(detail<=raw.length,'VHCG coarse table');
 const patches=new Int32Array(width*height).fill(-1);
 for(let index=0;index<patches.length;index++){
  const flag=raw[header+index*coarseRecordBytes+8];
  assert.ok(flag===0||flag===1,'VHCG detail flag');
  if(!flag)continue;
  patches[index]=detail;
  detail+=detailBytes;
 }
 assert.equal(detail,raw.length,'VHCG detail table');
 return {header,width,height,detailWidth,edge,originX,originY,patches};
}

function sampleVhcg(raw,grid,sourceX,sourceY){
 const x=(sourceX-grid.originX)/grid.edge,y=(sourceY-grid.originY)/grid.edge;
 const col=Math.floor(x),row=Math.floor(y);
 if(col<0||row<0||col>=grid.width||row>=grid.height)return [missingHeight,missingHeight];
 const index=row*grid.width+col,coarse=grid.header+index*coarseRecordBytes;
 const patch=grid.patches[index],water=raw.readFloatLE(coarse+4);
 if(patch<0)return [raw.readFloatLE(coarse),water];
 const dx=(x-col)*(grid.detailWidth-1),dy=(y-row)*(grid.detailWidth-1);
 assert.ok(Number.isInteger(dx)&&Number.isInteger(dy),'Navigation centers must fall on native VHCG vertices');
 return [raw.readFloatLE(patch+(dy*grid.detailWidth+dx)*4),water];
}

function encodeRuns(values){
 const runs=Buffer.alloc(values.length*runRecordBytes);
 let offset=0;
 for(let start=0;start<values.length;){
  const value=values[start];
  let end=start+1;
  while(end<values.length&&values[end]===value&&end-start<65535)end++;
  runs.writeUInt16LE(end-start,offset);
  runs.writeFloatLE(value,offset+2);
  offset+=runRecordBytes;
  start=end;
 }
 const lines=runs.subarray(0,offset).toString('base64').match(/.{1,120}/g);
 return "[\n"+lines.map(line=>" '"+line+"',").join('\n')+"\n].join('');\n";
}

export async function generateMapHeight742(grid=NAV_GRID){
 const sources=JSON.parse(await readFile(path.join(root,'docs/research/maps/7.42/terrain-sources.json'),'utf8'));
 const source=sources.resources.find(resource=>resource.vpkPath==='maps/dota.vhcg');
 const raw=await readFile(path.join(root,source.file));
 assert.equal(createHash('sha256').update(raw).digest('hex'),source.sha256,'VHCG snapshot hash');
 const vhcg=readVhcg(raw),ground=[],water=[];
 let validGround=0,validWater=0;
 for(let row=0;row<grid.rows;row++)for(let col=0;col<grid.cols;col++){
  const [solid,surface]=sampleVhcg(raw,vhcg,grid.origin.x+col*grid.cellSize-10464,10400-grid.origin.y-row*grid.cellSize);
  assert.ok(Number.isFinite(solid)&&Number.isFinite(surface),'VHCG samples must be finite');
  if(solid!==missingHeight)validGround++;
  if(surface!==missingHeight)validWater++;
  const index=ground.length;
  if(grid.blocked[index]==='0')assert.notEqual(solid,missingHeight,`Missing solid height at walkable navigation index ${index}`);
  ground.push(solid);
  water.push(surface);
 }
 const header='// Generated by docs/research/generate-map-height-742.mjs from maps/dota.vhcg.\n'+
  '// Each run is little-endian uint16 sample count followed by float32 Source elevation.\n'+
  `// Source SHA-256: ${source.sha256}\n\n`;
 await writeFile(path.join(root,'src/terrain-height-data.js'),header+
  'export const GROUND_HEIGHT_RUNS = '+encodeRuns(ground)+'\n'+
  'export const WATER_HEIGHT_RUNS = '+encodeRuns(water));
 console.log(`Generated Valve 7.42 height layers: ${validGround} solid and ${validWater} water samples at ${grid.cols}x${grid.rows} centers.`);
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await generateMapHeight742();
