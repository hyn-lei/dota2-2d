import fs from 'node:fs';
import assert from 'node:assert/strict';
import * as previous from '../../src/map-data.js';
import {generateTerrain742} from './generate-map-terrain-742.mjs';
const entities=JSON.parse(fs.readFileSync('docs/research/maps/7.42/entities.json','utf8'));
const hulls=JSON.parse(fs.readFileSync('docs/research/maps/7.42/spawn-hulls.json','utf8'));
const clean=s=>String(s||'').replace(/^\[PR#\]/,'');
const point=origin=>({x:origin[0]+10464,y:10400-origin[1]});
const located=(data,e)=>({...data,...point(e.origin),sourceX:e.origin[0],sourceY:e.origin[1],sourceZ:e.origin[2]});
const byName=new Map(entities.map(e=>[clean(e.targetname),e]));
const buildings=previous.BUILDING_LAYOUT.map(b=>{
 const source=entities.find(e=>clean(e.targetname)===b.id)||entities.find(e=>e.classname==='ent_dota_fountain'&&Number(e.teamnumber)-2===b.team&&b.kind==='fountain');
 assert.ok(source,`Missing source building ${b.id}`);return located(b,source);
});
const bases=[0,1].map(team=>{const fountain=buildings.find(b=>b.kind==='fountain'&&b.team===team);assert.ok(fountain,`Missing fountain ${team}`);return{x:fountain.x,y:fountain.y};});
const camps=previous.CAMP_LAYOUT.map(c=>{
 const source=entities.find(e=>e.classname==='npc_dota_neutral_spawner'&&clean(e.volumename)===c.sourceId),trigger=byName.get(c.sourceId);
 assert.ok(source&&trigger,`Missing source camp ${c.sourceId}`);
 const hull=hulls[trigger.model];assert.ok(hull,`Missing source spawn hull ${trigger.model}`);
 const yaw=(trigger.angles?.[1]||0)*Math.PI/180,cos=Math.cos(yaw),sin=Math.sin(yaw);
 const corners=[[hull.min[0],hull.min[1]],[hull.min[0],hull.max[1]],[hull.max[0],hull.max[1]],[hull.max[0],hull.min[1]]].map(([x,y])=>point([trigger.origin[0]+x*cos-y*sin,trigger.origin[1]+x*sin+y*cos,0]));
 const tier=Number(source.neutraltype),flooded=source.minspawntype==='7';
 return {...located(c,source),type:(flooded?'flooded_':'')+['small','medium','large','ancient'][tier],initialTier:tier,maxUpgradeCount:Number(source.maxupgradecount),minSpawnType:Number(source.minspawntype),maxSpawnType:Number(source.maxspawntype),ownerTeam:c.sourceId.includes('_good_')?0:1,area:flooded?'flooded':c.area==='flooded'?'jungle':c.area,spawnBox:corners};
});
const spawns=[[],[]],lanes=[[],[]];
for(let team=0;team<2;team++)for(const [lane,slug]of ['top','mid','bot'].entries()){
 const source=entities.find(e=>e.classname===`npc_dota_spawner_${team?'bad':'good'}_${slug}`);assert.ok(source);
 spawns[team][lane]=point(source.origin);const route=[point(source.origin)],seen=new Set();let next=clean(source.npcfirstwaypoint);
 while(next&&!seen.has(next)){seen.add(next);const corner=byName.get(next);if(!corner)break;route.push(point(corner.origin));next=clean(corner.target);}
 const fort=buildings.find(b=>b.kind==='ancient'&&b.team===1-team);route.push({x:fort.x,y:fort.y});lanes[team][lane]=route;
}
const trees=entities.filter(e=>e.classname==='ent_dota_tree').map(e=>({...point(e.origin),z:e.origin[2]}));
const objectives=structuredClone(previous.MAP_OBJECTIVES);
for(const [key,old]of Object.entries(objectives)){
 const classname=key==='ent_dota_shop'?'ent_dota_shop':key;
 const sources=entities.filter(e=>e.classname===classname);
 if(key==='npc_dota_roshan_spawner'){
  const second=entities.find(e=>e.classname==='info_player_start_dota'&&clean(e.targetname)==='roshan_location_2');
  if(sources[0])old[0]=located(old[0],sources[0]);if(second)old[1]=located(old[1],second);continue;
 }
 if(key==='npc_dota_miniboss_spawner'){
  const source=sources[0];if(source){const index=old.findIndex(e=>Math.hypot(e.sourceX-source.origin[0],e.sourceY-source.origin[1])<500);if(index>=0)old[index]=located(old[index],source);}continue;
 }
 assert.equal(sources.length,old.length,`Objective count ${key}`);
 for(let index=0;index<old.length;index++)old[index]=located(old[index],sources[index]);
}
let code=fs.readFileSync('src/map-data.js','utf8');
const version={...previous.MAP_VERSION,gameplay:'7.42',geometry:'7.41',entityGeometry:'7.42',entityExtractedAt:'2026-11-21',verifiedAt:'2026-11-21',steamBuild:26825343,geometryVerifiedAgainstCurrentBinary:false};
const updated={MAP_VERSION:version,BASES:bases,BUILDING_LAYOUT:buildings,CAMP_LAYOUT:camps,LANE_SPAWNS:spawns,TEAM_LANES:lanes,TREES:trees,MAP_OBJECTIVES:objectives};
for(const [name,value]of Object.entries(updated)){
 const expression=new RegExp(`export const ${name} = [^\\n]+;`);assert.ok(expression.test(code),`Missing export ${name}`);code=code.replace(expression,`export const ${name} = ${JSON.stringify(value)};`);
}
code=code.replace('Data extracted from the Dota 2 7.41 map, with gameplay target 7.41f.','Entity locations, trees and spawn hulls extracted from the Dota 2 7.42 client. Navigation/terrain raster retains the 7.41 snapshot.').replace('Generated by docs/research/generate-map-data.mjs; no positions are hand-placed.','Generated by docs/research/generate-map-data.mjs and generate-map-742.mjs; no positions are hand-placed.');
fs.writeFileSync('src/map-data.js',code);
await generateTerrain742();
fs.writeFileSync('docs/research/maps/7.42/runtime-extraction.json',JSON.stringify({patch:'7.42',steamBuild:26825343,counts:{buildings:buildings.length,camps:camps.length,trees:trees.length,laneSpawns:6},navigation:'Valve 7.42 shipped GridNav converted at exact existing world centers',updates:buildings.filter((b,i)=>b.x!==previous.BUILDING_LAYOUT[i].x||b.y!==previous.BUILDING_LAYOUT[i].y).map(b=>({id:b.id,x:b.x,y:b.y}))},null,2)+'\n');
console.log(`Updated ${buildings.length} buildings, ${camps.length} camps, ${trees.length} trees and six lane routes from the installed 7.42 client.`);
